def _ts_type(prop: dict, schemas: dict) -> str:
    if "$ref" in prop:
        return prop["$ref"].split("/")[-1]
    if "anyOf" in prop:
        parts = []
        for sub in prop["anyOf"]:
            t = _ts_type(sub, schemas)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    if "enum" in prop:
        vals = []
        for v in prop["enum"]:
            if isinstance(v, str):
                vals.append(f'"{v}"')
            elif v is None:
                vals.append("null")
            else:
                vals.append(str(v))
        return " | ".join(vals)
    typ = prop.get("type")
    if typ == "string":
        return "string"
    if typ in ("integer", "number"):
        return "number"
    if typ == "boolean":
        return "boolean"
    if typ == "null":
        return "null"
    if typ == "array":
        item_type = _ts_type(prop.get("items", {}), schemas)
        if "|" in item_type:
            return f"Array<{item_type}>"
        return f"{item_type}[]"
    if typ == "object":
        add = prop.get("additionalProperties")
        if isinstance(add, dict):
            return f"Record<string, {_ts_type(add, schemas)}>"
        return "Record<string, unknown>"
    return "unknown"


