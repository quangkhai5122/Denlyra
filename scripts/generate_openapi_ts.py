def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated TS matches OpenAPI")
    args = parser.parse_args()

    local = ROOT / "local_data"
    local.mkdir(exist_ok=True)
    scratch = Path(tempfile.mkdtemp(prefix="openapi-ts-", dir=local))
    try:
        app = create_app(
            Settings(
                demo_mode=True,
                db_url="sqlite+pysqlite:///:memory:",
                archive_dir=str(scratch / "archive"),
            )
        )
        schema = app.openapi()
    finally:
        shutil.rmtree(scratch, ignore_errors=True)

    rendered = render_typescript(schema)
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != rendered:
            raise SystemExit(
                "OpenAPI TS client stale: run python scripts/generate_openapi_ts.py"
            )
        print(f"OpenAPI TS client PASS: {TARGET.relative_to(ROOT)} matches live FastAPI schema")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"Generated {TARGET.relative_to(ROOT)} ({len(schema.get('paths', {}))} paths)")


if __name__ == "__main__":
    main()
